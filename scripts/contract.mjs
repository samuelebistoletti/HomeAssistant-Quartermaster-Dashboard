#!/usr/bin/env node
// Turn the integration's sample snapshot (tests/snapshot_sample.json in
// HomeAssistant-Quartermaster) into tests/contract.generated.ts, where
// `satisfies` makes `tsc` check it against src/types.ts: a missing field,
// an unknown one or a value of the wrong type fails `npm run lint`.
//
//   npm run contract            read the sibling checkout of the integration
//   npm run contract -- --main  read main on GitHub (what CI does)
//   add --check                 fail if the committed file differs
import { readFile, writeFile } from "node:fs/promises";

const SIBLING = new URL("../../HomeAssistant-Quartermaster/tests/snapshot_sample.json", import.meta.url);
const MAIN =
  "https://raw.githubusercontent.com/samuelebistoletti/HomeAssistant-Quartermaster/main/tests/snapshot_sample.json";
const TARGET = new URL("../tests/contract.generated.ts", import.meta.url);

const args = new Set(process.argv.slice(2));
const text = args.has("--main")
  ? await fetch(MAIN).then((response) => {
      if (!response.ok) {
        throw new Error(`${MAIN}: HTTP ${response.status}`);
      }
      return response.text();
    })
  : await readFile(SIBLING, "utf8");
const sample = JSON.parse(text);

const output = `// Generated by scripts/contract.mjs from the integration's
// tests/snapshot_sample.json: do not edit, run \`npm run contract\`.
import type { JournalEntry, Snapshot } from "../src/types";

export const SNAPSHOT = ${JSON.stringify(sample.snapshot, null, 2)} satisfies Snapshot;

export const JOURNAL = ${JSON.stringify(sample.journal.entries, null, 2)} satisfies JournalEntry[];
`;

if (args.has("--check")) {
  const current = await readFile(TARGET, "utf8").catch(() => "");
  if (current !== output) {
    console.error(
      "tests/contract.generated.ts does not match the integration's sample snapshot: " +
        "run 'npm run contract', update src/types.ts until 'npm run lint' passes, and commit.",
    );
    process.exit(1);
  }
} else {
  await writeFile(TARGET, output);
}
